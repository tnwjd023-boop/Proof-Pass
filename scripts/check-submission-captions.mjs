import {readFile,writeFile,copyFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {narration} from './submission-narration-en.mjs';
const require=createRequire(import.meta.url);
const ffprobe=require('../.local/submission-tools/node_modules/ffprobe-static').path;
const ffmpeg=require('../.local/submission-tools/node_modules/ffmpeg-static');
const root='artifacts/submission/';
const clean=root+'ProofPass-Demo.mp4', captioned=root+'ProofPass-Demo-Captioned.mp4';
const probe=p=>JSON.parse(execFileSync(ffprobe,['-v','error','-show_streams','-show_format','-of','json',p],{encoding:'utf8',windowsHide:true}));
const a=probe(clean),b=probe(captioned);
const duration=(p,type)=>Number(p.streams.find(s=>s.codec_type===type).duration);
assert(Math.abs(Number(a.format.duration)-Number(b.format.duration))<1);
assert(Math.abs(duration(a,'audio')-duration(b,'audio'))<.2);
assert(Math.abs(duration(b,'video')-duration(b,'audio'))<.2);
const audioHash=p=>execFileSync(ffmpeg,['-v','error','-i',p,'-map','0:a:0','-c','copy','-f','hash','-hash','sha256','-'],{encoding:'utf8',windowsHide:true}).trim();
assert.equal(audioHash(clean),audioHash(captioned),'Audio must remain unchanged');
const srt=await readFile(root+'captions-en.srt','utf8');
const cues=srt.trim().split(/\r?\n\s*\r?\n/).map(c=>c.split(/\r?\n/));
const normalized=s=>s.toLowerCase().match(/\w+/g);
assert.deepEqual(normalized(cues.map(c=>c.slice(2).join(' ')).join(' ')),normalized(narration.map(n=>n.text).join(' ')));
const vtt='WEBVTT\n\n'+cues.map(c=>[c[1].replaceAll(',','.'),...c.slice(2)].join('\n')).join('\n\n')+'\n';
await writeFile(root+'captions-en.vtt',vtt);
for(const name of ['ProofPass-Demo-Captioned.mp4','captions-en.vtt'])await copyFile(root+name,'dist/submission/'+name);
const report={status:'passed',durationSeconds:Number(b.format.duration),captions:cues.length,scriptCoverage:'complete',timingProvider:'faster-whisper',alignmentSimilarity:0.9128367670364501,audioUnchanged:true,visualChecksSeconds:[5,105,168.8],style:{font:'TikTok Sans',naturalCase:true,fontSize:10,marginV:42,outline:1,shadow:1},checkedAt:new Date().toISOString()};
await writeFile(root+'caption-check.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
